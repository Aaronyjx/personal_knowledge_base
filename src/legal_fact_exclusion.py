# 固定期限合同例外
# ============================================================

def extract_fixed_term_exception_fact(
    question: str,
) -> bool | None:
    """
    提取：

        劳动者提出订立固定期限劳动合同

    相关事实。

    返回：

        True
            用户明确表达劳动者提出/要求订立固定期限劳动合同。

        False
            用户明确表达劳动者没有提出/要求订立固定期限劳动合同。

        None
            用户没有明确表达。

    注意：

        负面事实优先。

    例如：

        劳动者没有提出订立固定期限劳动合同

    应得到：

        False

    而不能因为文本同时包含：

        提出订立固定期限劳动合同

    就错误得到：

        True
    """

    text = normalize_text(question)

    # --------------------------------------------------------
    # 负面事实优先
    # --------------------------------------------------------

    if contains_any(
        text,
        FIXED_TERM_EXCEPTION_NEGATIVE_PATTERNS,
    ):
        return False

    # --------------------------------------------------------
    # 正面事实
    # --------------------------------------------------------

    if contains_any(
        text,
        FIXED_TERM_EXCEPTION_PATTERNS,
    ):
        return True

    return None


