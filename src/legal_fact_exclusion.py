# ============================================================
# 通用 Article 事实识别
# ============================================================

def _extract_article_fact(
    text: str,
    negative_patterns: List[str],
    positive_patterns: List[str],
) -> str | None:
    """
    提取单个法律条款对应的明确事实。

    返回：

        "negative"
            用户明确表达不存在该条款规定情形。

        "positive"
            用户明确表达存在该条款规定情形。

        None
            用户没有明确表达。

    注意：

        negative 优先。

    这是为了避免：

        “不存在……第三十九条……情形”

    被 positive pattern 中的：

        “第三十九条规定的情形”

    错误捕获。
    """

    if contains_any(
        text,
        negative_patterns,
    ):
        return "negative"

    if contains_any(
        text,
        positive_patterns,
    ):
        return "positive"

    return None


# ============================================================
# Article 39
# ============================================================

def extract_article_39_fact(
    question: str,
) -> bool | None:
    """
    提取《劳动合同法》第三十九条相关事实。

    返回：

        True
            明确存在第三十九条规定的情形。

        False
            明确不存在第三十九条规定的情形。

        None
            未明确表达。
    """

    text = normalize_text(question)

    result = _extract_article_fact(
        text,
        ARTICLE_39_NEGATIVE_PATTERNS,
        ARTICLE_39_POSITIVE_PATTERNS,
    )

    if result == "negative":
        return False

    if result == "positive":
        return True

    return None


