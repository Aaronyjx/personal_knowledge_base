def contains_any(
    text: str,
    patterns: List[str],
) -> bool:
    """
    判断文本是否包含任意模式。

    注意：

        事实提取层使用与 V6.0-27 Engine
        相同的标准化规则。
    """

    normalized = normalize_text(text)

    return any(
        normalize_text(pattern)
        in normalized
        for pattern in patterns
    )


def unique_texts(
    values: List[str],
) -> List[str]:
    """
    去重并保持原顺序。
    """

    result: List[str] = []

    seen = set()

    for value in values:

        if value in seen:
            continue

        seen.add(value)

        result.append(value)

    return result


