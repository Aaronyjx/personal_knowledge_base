# ============================================================
# Contract Sequence Extraction
# ============================================================

def extract_contract_sequence(
    question: str,
) -> Optional[ContractSequence]:
    """
    提取合同序列。

    规则：

        三次固定期限
            → count = 3

        两次固定期限 + 明确后续续订/续签
            → count = 3

        两次固定期限
            → count = 2
    """

    text = normalize_text(question)

    three_contract_patterns = [
        "连续签订三次固定期限劳动合同",
        "连续订立三次固定期限劳动合同",
        "连续签了三次固定期限劳动合同",
        "连续签订了三次固定期限劳动合同",
        "连续订立了三次固定期限劳动合同",
    ]

    if contains_any(
        text,
        three_contract_patterns,
    ):

        return ContractSequence(
            count=3,
            term_type="fixed",
            continuous=True,
        )

    two_contract_patterns = [
        "连续签订两次固定期限劳动合同",
        "连续订立两次固定期限劳动合同",
        "连续签了两次固定期限劳动合同",
        "连续签订了两次固定期限劳动合同",
        "连续订立了两次固定期限劳动合同",
    ]

    if contains_any(
        text,
        two_contract_patterns,
    ):

        if has_completed_renewal(text):

            return ContractSequence(
                count=3,
                term_type="fixed",
                continuous=True,
            )

        later_renewal_patterns = [
            "后来续订",
            "后来续签",
            "之后续订",
            "之后续签",
            "又续订",
            "又续签",
        ]

        if contains_any(
            text,
            later_renewal_patterns,
        ):

            return ContractSequence(
                count=3,
                term_type="fixed",
                continuous=True,
            )

        return ContractSequence(
            count=2,
            term_type="fixed",
            continuous=True,
        )

    return None


# ============================================================
# Legal Facts Extraction
# ============================================================

def extract_legal_facts(
    question: str,
) -> LegalFacts:
    """
    V6.1 第二阶段：

    将现有事实提取结果统一组装成 LegalFacts。

    --------------------------------------------------------
    重要设计原则
    --------------------------------------------------------

    本函数不重新实现事实识别规则。

    事实识别仍然由：

        extract_explicit_facts()
        extract_contract_sequence()
        has_completed_renewal()

    完成。

    本函数只负责：

        “把已经识别出来的事实放入 LegalFacts”。

    这样可以保证整个系统只有一套事实识别规则。

    --------------------------------------------------------
    Fact 层三态语义
    --------------------------------------------------------

        True
            明确存在 / 明确发生

        False
            明确不存在 / 明确未发生

        None
            未明确说明

    --------------------------------------------------------
    与 Condition 层的关系
    --------------------------------------------------------

    例如：

        article_39 = True

    只表示：

        用户明确说存在第三十九条情形。

    Legal Decision Engine 后续才负责将其转换成：

        EXCLUSION
        NOT_SATISFIED

    同理：

        article_39 = False

    后续转换为：

        EXCLUSION
        SATISFIED

    而：

        article_39 = None

    后续转换为：

        EXCLUSION
        UNKNOWN
    """

    # --------------------------------------------------------
    # 第一步：复用已经验证过的事实提取逻辑
    # --------------------------------------------------------

    explicit_facts = extract_explicit_facts(
        question
    )

    contract_sequence = extract_contract_sequence(
        question
    )

    completed_renewal = (
        True
        if has_completed_renewal(question)
        else None
    )

    # --------------------------------------------------------
    # 第二步：从 explicit_facts 读取结构化事实
    #
    # 注意：
    #
    # 不重新扫描 question。
    #
    # 这样可以保证：
    #
    #   extract_explicit_facts()
    #           ↓
    #       唯一事实来源
    # --------------------------------------------------------

    worker_agreement = None

    if (
        "劳动者明确提出或者同意续订、订立劳动合同"
        in explicit_facts
    ):

        worker_agreement = True

    # --------------------------------------------------------
    # Article 39
    # --------------------------------------------------------

    article_39 = None

    if (
        "劳动者存在《劳动合同法》第三十九条规定的情形"
        in explicit_facts
    ):

        article_39 = True

    elif (
        "劳动者不存在《劳动合同法》第三十九条规定的情形"
        in explicit_facts
    ):

        article_39 = False

    # --------------------------------------------------------
    # Article 40(1)
    # --------------------------------------------------------

    article_40_1 = None

    if (
        "劳动者存在《劳动合同法》第四十条第一项规定的情形"
        in explicit_facts
    ):

        article_40_1 = True

    elif (
        "劳动者不存在《劳动合同法》第四十条第一项规定的情形"
        in explicit_facts
    ):

        article_40_1 = False

    # --------------------------------------------------------
    # Article 40(2)
    # --------------------------------------------------------

    article_40_2 = None

    if (
        "劳动者存在《劳动合同法》第四十条第二项规定的情形"
        in explicit_facts
    ):

        article_40_2 = True

    elif (
        "劳动者不存在《劳动合同法》第四十条第二项规定的情形"
        in explicit_facts
    ):

        article_40_2 = False

    # --------------------------------------------------------
    # Fixed-Term Exception
    # --------------------------------------------------------

    fixed_term_exception = None

    if (
        "劳动者提出订立固定期限劳动合同"
        in explicit_facts
    ):

        fixed_term_exception = True

    elif (
        "劳动者没有提出订立固定期限劳动合同"
        in explicit_facts
    ):

        fixed_term_exception = False

    # --------------------------------------------------------
    # 构造 LegalFacts
    # --------------------------------------------------------

    return LegalFacts(
        explicit_facts=explicit_facts,
        contract_sequence=contract_sequence,
        completed_renewal=completed_renewal,
        worker_agreement=worker_agreement,
        article_39=article_39,
        article_40_1=article_40_1,
        article_40_2=article_40_2,
        fixed_term_exception=fixed_term_exception,
    )