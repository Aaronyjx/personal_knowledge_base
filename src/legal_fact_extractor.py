        "已续签",

        "后来已经续订劳动合同",
        "后来已经续签劳动合同",

        "后来已经续订了劳动合同",
        "后来已经续签了劳动合同",

        "之后已经续订劳动合同",
        "之后已经续签劳动合同",

        "之后已经续订了劳动合同",
        "之后已经续签了劳动合同",

        "之后续订劳动合同",
        "之后续签劳动合同",

        "之后续订了劳动合同",
        "之后续签了劳动合同",

        "后来又续订劳动合同",
        "后来又续签劳动合同",

