# ============================================================
# Completed Renewal Detection
# ============================================================

def has_completed_renewal(
    question: str,
) -> bool:
    """
    判断问题中是否存在明确的“已经完成续订/续签”事实。

    重要原则：

        “准备续订”
        “计划续订”
        “打算续订”
        “拟续订”

    均不能视为已经完成续订。

    同样：

        “劳动者同意续订”

    只能证明劳动者同意，
    不能单独证明续订已经完成。
    """

    text = normalize_text(question)

    renewal_patterns = [

        "已经续订劳动合同",
        "已经续签劳动合同",

        "已经续订了劳动合同",
        "已经续签了劳动合同",

        "已续订劳动合同",
        "已续签劳动合同",

        "已经续订",
        "已经续签",

        "已续订",
        "已续签",

        "后来已经续订劳动合同",
        "后来已经续签劳动合同",

        "后来已经续订了劳动合同",
        "后来已经续签了劳动合同",

        "之后已经续订劳动合同",
        "之后已经续签劳动合同",

        "之后已经续订了劳动合同",
        "之后已经续签了劳动合同",

        "之后续订劳动合同",
        "之后续签劳动合同",

        "之后续订了劳动合同",
        "之后续签了劳动合同",

        "后来又续订劳动合同",
        "后来又续签劳动合同",

        "后来又续订了劳动合同",
        "后来又续签了劳动合同",

        "之后又已经续订劳动合同",
        "之后又已经续签劳动合同",

        "第三次已经续订",
        "第三次已经续签",

        "第三次已续订",
        "第三次已续签",

        "第三次已经续订劳动合同",
        "第三次已经续签劳动合同",

        "第三次已续订劳动合同",
        "第三次已续签劳动合同",
    ]

    return contains_any(
        text,
        renewal_patterns,
    )


