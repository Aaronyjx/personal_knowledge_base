# ============================================================
# Contract Sequence Extraction
# ============================================================

def extract_contract_sequence(
    question: str,
) -> Optional[ContractSequence]:
    """
    提取合同序列。

    规则：

        三次固定期限
            → count = 3

        两次固定期限 + 明确后续续订/续签
            → count = 3

        两次固定期限
            → count = 2
    """

    text = normalize_text(question)

    three_contract_patterns = [
        "连续签订三次固定期限劳动合同",
        "连续订立三次固定期限劳动合同",
        "连续签了三次固定期限劳动合同",
        "连续签订了三次固定期限劳动合同",
        "连续订立了三次固定期限劳动合同",
    ]

    if contains_any(
        text,
        three_contract_patterns,
    ):

        return ContractSequence(
            count=3,
            term_type="fixed",
            continuous=True,
        )

    two_contract_patterns = [
        "连续签订两次固定期限劳动合同",
        "连续订立两次固定期限劳动合同",
        "连续签了两次固定期限劳动合同",
        "连续签订了两次固定期限劳动合同",
        "连续订立了两次固定期限劳动合同",
    ]

    if contains_any(
        text,
        two_contract_patterns,
    ):

        if has_completed_renewal(text):

            return ContractSequence(
                count=3,
                term_type="fixed",
                continuous=True,
            )

        later_renewal_patterns = [
            "后来续订",
            "后来续签",
            "之后续订",
            "之后续签",
            "又续订",
            "又续签",
        ]

        if contains_any(
            text,
            later_renewal_patterns,
        ):

            return ContractSequence(
                count=3,
                term_type="fixed",
                continuous=True,
            )

        return ContractSequence(
            count=2,
            term_type="fixed",
            continuous=True,
        )

    return None
