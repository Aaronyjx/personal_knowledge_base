def has_worker_agreement(
    question: str,
) -> bool:
    """
    判断用户问题中是否明确表达：

        劳动者提出或者同意续订、续签、订立劳动合同。

    返回：

        True
            用户明确表达劳动者提出或者同意。

        False
            用户没有明确表达该事实。

    注意：

        本函数只识别事实。

        返回 True 并不意味着：

            “劳动者提出或者同意续订、订立劳动合同”

        这一法律条件已经由 Decision Engine 判定为
        SATISFIED。

    后续仍由：

        Legal Decision Engine

    将：

        worker_agreement = True

    映射为相应 ConditionResult。

    ========================================================
    事实与法律条件的隔离
    ========================================================

    例如：

        用户问题：

        公司连续签订三次固定期限劳动合同，
        员工也同意续订。

    本函数只返回：

        True

    LegalFacts 最终记录：

        worker_agreement = True

    然后由：

        Legal Decision Engine

    决定：

        “劳动者提出或者同意续订、订立劳动合同”

    的 ConditionResult。
    """

    text = normalize_text(question)

    return contains_any(
        text,
        WORKER_AGREEMENT_PATTERNS,
    )


# ============================================================
# 统一提取续订相关事实
# ============================================================

def extract_renewal_facts(
    question: str,
) -> Dict[str, bool]:
    """
    提取续订相关事实。

    返回：

        {
            "completed_renewal": bool,
            "worker_agreement": bool,
        }

    例如：

        公司已经续订劳动合同，
        劳动者也同意续订。

    返回：

        {
            "completed_renewal": True,
            "worker_agreement": True,
        }

    ========================================================
    注意
    ========================================================

    这里返回的是：

        事实识别结果

    不是：

        法律条件结果。

    因此：

        True

    只代表：

        用户明确表达了该事实。

    不代表：

        法律条件已经满足。

    ========================================================
    与 LegalFacts 的关系
    ========================================================

    LegalFacts 中：

        completed_renewal
        worker_agreement

    最终由：

        legal_fact_extractor.py

    进行组装。

    本函数属于统一事实识别接口，
    便于后续测试和模块化调用。
    """

    text = normalize_text(question)

    return {
        "completed_renewal": has_completed_renewal(text),
        "worker_agreement": has_worker_agreement(text),
    }