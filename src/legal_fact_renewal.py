# ============================================================
# 已完成续订 / 续签事实
# ============================================================

def has_completed_renewal(
    question: str,
) -> bool:
    """
    判断用户问题中是否明确表达已经完成劳动合同续订/续签。

    只有明确表示已经发生续订/续签的表达才返回 True。

    例如：

        已经续订劳动合同
        已经续签劳动合同
        已续订劳动合同
        已续签劳动合同
        后来已经续订劳动合同
        之后已经续签劳动合同
        第三次已经续订劳动合同

    返回：

        True
            明确存在已经完成的续订/续签事实。

        False
            没有明确表达已经完成续订/续签。

    特别注意：

        “准备续订”
        “计划续订”
        “打算续订”
        “拟续订”

    不属于已经完成的续订事实。

    同样：

        “劳动者同意续订”

    只能证明劳动者同意续订，
    不能单独证明劳动合同已经完成续订。

    ========================================================
    重要边界
    ========================================================

    本函数只做：

        事实识别

    不做：

        法律条件判断。

    例如：

        公司已经续订劳动合同

    只能识别：

        completed_renewal = True

    不能因此判断：

        “续订劳动合同” Condition = SATISFIED

    Condition 状态由：

        Legal Decision Engine

    根据 LegalFacts 统一判断。
    """

    text = normalize_text(question)

    # --------------------------------------------------------
    # 已经完成续订 / 续签
    # --------------------------------------------------------

    renewal_patterns: List[str] = [
        "已经续订劳动合同",
        "已经续签劳动合同",
        "已经续订了劳动合同",
        "已经续签了劳动合同",
        "已续订劳动合同",
        "已续签劳动合同",
        "已经续订",
        "已经续签",
        "已续订",
        "已续签",
        "后来已经续订劳动合同",
        "后来已经续签劳动合同",
        "后来已经续订了劳动合同",
        "后来已经续签了劳动合同",
        "之后已经续订劳动合同",
        "之后已经续签劳动合同",
        "之后已经续订了劳动合同",
        "之后已经续签了劳动合同",
        "之后续订劳动合同",
        "之后续签劳动合同",
        "之后续订了劳动合同",
        "之后续签了劳动合同",
        "后来又续订劳动合同",
        "后来又续签劳动合同",
        "后来又续订了劳动合同",
        "后来又续签了劳动合同",
        "之后又已经续订劳动合同",
        "之后又已经续签劳动合同",
        "之后又已经续订了劳动合同",
        "之后又已经续签了劳动合同",
        "第三次已经续订",
        "第三次已经续签",
        "第三次已续订",
        "第三次已续签",
        "第三次已经续订劳动合同",
        "第三次已经续签劳动合同",
        "第三次已续订劳动合同",
        "第三次已续签劳动合同",
    ]

    return contains_any(
        text,
        renewal_patterns,
    )


