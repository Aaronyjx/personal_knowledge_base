# -*- coding: utf-8 -*-

"""
RAG V6.0-27

Legal Answer Sanitizer

============================================================
功能
============================================================

负责对 Ollama / LLM 输出进行纯文本结构清理。

本模块只负责：

1. 清理空结果
2. 基础文本规范化
3. 删除 Qwen / Ollama Thinking 内容
4. 删除 Markdown 标题符号
5. 压缩连续空行
6. 截取正式法律回答 Section
7. 删除重复 Section

============================================================
重要边界
============================================================

本模块只进行 Answer Sanitization。

不负责：

- 法律事实判断
- 用户事实验证
- 法律条件判断
- DecisionResult 生成
- Decision 一致性验证
- 法律依据验证
- 法律引用验证
- 最终 Validation
- Ollama 调用
- 法律结论重新计算

例如：

    UNKNOWN
    SATISFIED
    NOT_SATISFIED
    DEFINITE
    CONDITIONAL
    NOT_ESTABLISHED

都不会在这里重新计算。

============================================================
设计原则
============================================================

Answer Sanitizer 的职责是：

    LLM 原始输出
        ↓
    结构清理
        ↓
    干净的最终答案文本

而不是：

    LLM 原始输出
        ↓
    重新判断法律结论

============================================================
版本
============================================================

V6.0-27
"""


import re


from src.legal_common import (
    normalize_text,
)


# ============================================================
# 正式回答 Section
# ============================================================

SECTION_CONCLUSION = "【结论】"
SECTION_BASIS = "【法律依据】"
SECTION_ANALYSIS = "【法律分析】"
SECTION_NOTICE = "【需要注意】"


REQUIRED_SECTIONS = [
    SECTION_CONCLUSION,
    SECTION_BASIS,
    SECTION_ANALYSIS,
    SECTION_NOTICE,
]


# ============================================================
# 清理 Ollama 输出
# ============================================================

def clean_answer(
    answer: str,
) -> str:
    """
    清理 Ollama / LLM 输出。

    ========================================================
    清理内容
    ========================================================

    1. 空结果处理。

    2. 基础文本规范化。

    3. 删除 Qwen Thinking 内容。

    4. 删除 Markdown 标题符号。

    5. 压缩连续空行。

    6. 如果已经生成正式 Section，
       从第一个正式 Section 开始保留。

    7. 删除重复 Section。

    ========================================================
    注意
    ========================================================

    本函数不进行法律判断。

    例如：

        UNKNOWN
        SATISFIED
        NOT_SATISFIED
        DEFINITE
        CONDITIONAL
        NOT_ESTABLISHED

    都不会在这里重新计算。

    ========================================================
    """

    if not answer:
        return ""

    # ========================================================
    # 基础文本规范化
    # ========================================================

    answer = normalize_text(
        answer
    )

    # ========================================================
    # 删除 Qwen Thinking 内容
    #
    # 第一种：
    #
    #     <think>
    #         ...
    #     </think>
    #
    # 第二种：
    #
    #     <think>
    #         ...
    #
    # 即没有闭合 </think>。
    # ========================================================

    answer = re.sub(
        r"<think>.*?</think>",
        "",
        answer,
        flags=re.DOTALL,
    )

    answer = re.sub(
        r"<think>.*",
        "",
        answer,
        flags=re.DOTALL,
    )

    answer = answer.strip()

    # ========================================================
    # 删除 Markdown 标题符号
    #
    # 例如：
    #
    #     # 【结论】
    #
    #     ## 【法律依据】
    #
    # 转换为：
    #
    #     【结论】
    #
    #     【法律依据】
    # ========================================================

    answer = re.sub(
        r"(?m)^\s*#+\s*【",
        "【",
        answer,
    )

    # ========================================================
    # 多个空行压缩
    #
    # 最多保留一个空白行。
    # ========================================================

    answer = re.sub(
        r"\n{3,}",
        "\n\n",
        answer,
    )

    # ========================================================
    # 如果四段标题存在，
    # 从第一个正式 Section 开始保留。
    #
    # 例如 Ollama 可能输出：
    #
    #     以下是法律分析：
    #
    #     【结论】
    #     ...
    #
    # 则删除正式 Section 之前的说明文字。
    # ========================================================

    positions = []

    for section in REQUIRED_SECTIONS:

        position = answer.find(
            section
        )

        if position >= 0:

            positions.append(
                position
            )

    if positions:

        start = min(
            positions
        )

        answer = answer[
            start:
        ]

    # ========================================================
    # 删除重复标题
    # ========================================================

    answer = remove_duplicate_sections(
        answer
    )

    return answer.strip()


# ============================================================
# 删除重复 Section
# ============================================================

def remove_duplicate_sections(
    text: str,
) -> str:
    """
    删除重复的最终回答 Section。

    例如 Ollama 可能生成：

        【结论】
        ...

        【法律依据】
        ...

        【法律分析】
        ...

        【需要注意】
        ...

        【结论】
        ...

    最终只保留第一次出现的：

        【结论】

    ========================================================
    注意
    ========================================================

    这里仅进行文本结构清理。

    不判断：

        - 哪一个结论正确
        - 哪一个法律依据正确
        - 哪一个条件正确
        - 哪一个 Decision 正确

    ========================================================
    """

    if not text:
        return ""

    # ========================================================
    # 识别正式回答 Section
    # ========================================================

    pattern = (
        r"(【结论】|【法律依据】|【法律分析】|【需要注意】)"
    )

    parts = re.split(
        pattern,
        text,
    )

    # 没有形成有效 Section 结构时，
    # 原样返回。
    if len(parts) < 3:
        return text

    result = []

    seen = set()

    i = 0

    while i < len(parts):

        part = parts[i]

        # ====================================================
        # 当前部分是正式 Section
        # ====================================================

        if part in REQUIRED_SECTIONS:

            section_name = part

            body = ""

            if i + 1 < len(parts):

                body = parts[
                    i + 1
                ]

            # =================================================
            # 第一次出现的 Section 才保留。
            #
            # 后续同名 Section 整段删除。
            # =================================================

            if section_name not in seen:

                result.append(
                    section_name
                )

                result.append(
                    body
                )

                seen.add(
                    section_name
                )

            i += 2

        else:

            # ------------------------------------------------
            # 正式 Section 之前的普通文本，
            # 只保留第一次出现的前置文本。
            #
            # 正常情况下 clean_answer() 已经会在正式
            # Section 存在时将其截掉。
            #
            # 这里保留原有实现行为，避免改变回归结果。
            # ------------------------------------------------

            if (
                part.strip()
                and not result
            ):

                result.append(
                    part
                )

            i += 1

    return "".join(
        result
    ).strip()


